"""gen_tahoe_fwd.py BINARY MISSING_SYMBOLS OUT_HEADER — writes pga_tahoe_fwd.h for PG106Accel.

The same mechanism as kexts/NVRM/accel/gen_tahoe_fwd.py (read its docstring): macOS 26 stopped exporting some
IOAcceleratorFamily2 methods that only fill inherited vtable slots, so each such slot gets an override that jumps
through the base class's exported vtable. BINARY is a bootstrap build (-DPGA_FWD_BOOTSTRAP, no forwards);
MISSING_SYMBOLS lists the imports macOS 26 does not export. The slots depend on which methods PG106Accel's own
classes override, so the header is generated from this kext's binary, not copied from NVAccel's."""
import os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ACCEL = os.path.join(HERE, '..', 'NVRM', 'accel')
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools'))
from vtdump import vtables
BASES = {'PG106AccelResource': 'IOAccelResource2', 'PG106AccelSysMemory': 'IOAccelSysMemory',
         'PG106AccelVidMemory': 'IOAccelVidMemory', 'PG106AccelSurface': 'IOAccelLegacySurface',
         'PG106AccelGLContext': 'IOAccelGLContext2', 'PG106Accel2DContext': 'IOAccel2DContext2',
         'PG106AccelCLContext': 'IOAccelCLContext2', 'PG106AccelVideoContext': 'IOAccelVideoContext2',
         'PG106AccelEventMachine': 'IOAccelEventMachineFast2', 'PG106AccelDisplayMachine': 'IOAccelLegacyDisplayMachine',
         'PG106AccelDisplayPipe': 'IOAccelLegacyDisplayPipe',
         'PG106AccelTask': 'IOAccelTask', 'PG106AccelMemoryMap': 'IOAccelMemoryMap', 'PG106Accel': 'IOGraphicsAccelerator2'}
def decls():
    out = {}
    for sub in ('iofam', 're'):
        for f in sorted(os.listdir(os.path.join(ACCEL, sub))):
            if not f.endswith('.h'): continue
            cls = f[:-2]
            for l in open(os.path.join(ACCEL, sub, f)):
                m = re.match(r'\s*virtual\s+(.+?)\s+([A-Za-z_]\w*)\((.*?)\)(\s*const)?\s*(= 0)?\s*(APPLE_KEXT_OVERRIDE)?\s*;', l)
                if m:
                    args = [a.strip() for a in m.group(3).split(',')] if m.group(3).strip() else []
                    out.setdefault((cls, m.group(2), len(args), bool(m.group(4))), (m.group(1).strip(), args))
    return out
def main(binary, missfile, outpath):
    miss = {l.strip() for l in open(missfile) if l.strip()}
    vt = vtables(binary); d = decls()
    dem = lambda xs: subprocess.run(['c++filt', '-_'], input='\n'.join(xs), capture_output=True, text=True).stdout.split('\n')
    h = ['// GENERATED by gen_tahoe_fwd.py from a PG106Accel bootstrap build for macOS 26 (Tahoe). Do not edit;',
         '// kexts/PG106Accel/cross-build.sh regenerates it and fails when this copy is stale.',
         '#pragma once', '#ifndef PGA_FWD_BOOTSTRAP']
    defs = []; n = 0; covered = set()
    for cls, base in BASES.items():
        slots = vt.get('%d%s' % (len(cls), cls))
        if slots is None: sys.exit('no vtable for %s in %s' % (cls, binary))
        lines = []
        for idx, (sym, dn) in enumerate(zip(slots, dem(slots))):
            if sym not in miss: continue
            m = re.match(r'(\w+)::(\w+)\((.*)\)( const)?$', dn)
            if not m: sys.exit('cannot parse %s' % dn)
            owner, name, const = m.group(1), m.group(2), bool(m.group(4))
            arity = 0 if not m.group(3).strip() else m.group(3).count(',') + 1
            if (owner, name, arity, const) not in d: sys.exit('no declaration of %s in the reconstructed headers' % dn)
            ret, args = d[(owner, name, arity, const)]
            params = ', '.join('%s a%d' % (a, i) for i, a in enumerate(args))
            c = ' const' if const else ''
            lines.append('    %s %s(%s)%s override;' % (ret, name, params, c))
            defs.append('__attribute__((naked)) %s %s::%s(%s)%s { __asm__("movq __ZTV%d%s@GOTPCREL(%%rip), %%r11\\n\\tjmpq *%d(%%r11)"); }'
                        % (ret, cls, name, params, c, len(base), base, 8 * (2 + idx)))
            covered.add(sym); n += 1
        h.append('#define PGA_FWD_%s \\\n%s' % (cls, ' \\\n'.join(lines) if lines else ''))
    h.append('#define PGA_FWD(cls) PGA_FWD_##cls')
    h += ['#define PGA_FWD_DEFS \\'] + ['%s \\' % x for x in defs] + ['/* %d forwarded slots */' % n]
    h += ['#else', '#define PGA_FWD(cls)', '#define PGA_FWD_DEFS', '#endif']
    open(outpath, 'w').write('\n'.join(h) + '\n')
    print('pga_tahoe_fwd.h: %d forwarded slots; %d missing import(s) are not vtable slots' % (n, len(miss - covered)))
    for s in sorted(miss - covered): print('   not a slot:', s)
if __name__ == '__main__': main(sys.argv[1], sys.argv[2], sys.argv[3])
