"""gen-firmware-embed.py — generate the C file that embeds the GP106 firmware
PG106.kext needs into its binary.

An OpenCore-injected kext has no bundle on disk, so OSKextRequestResource can
never deliver Contents/Resources (macOS 26.7.2, first boot: kernelmanagerd
"Unable to create bundle at path /Library/Extensions/PG106.kext" for all 17
requests). The firmware therefore travels inside the binary, as a table of
const arrays (pg106_fw_embedded.h), one entry per pg106_devboot_fw_names
row of pascal/core/src/devboot.c, in that order.

Every file is checked against the pinned list pascal/kext/firmware.sha256
(the exact linux-firmware bytes; see research/firmware/gp106/README.md) and
embedded unmodified. A missing or mismatching file fails the build unless
--allow-missing is given (then the entry is left out and the kext falls back
to OSKextRequestResource for it, which only works from /Library/Extensions).

usage: gen-firmware-embed.py OUT.c [--firmware DIR] [--sha256 FILE]
                             [--devboot FILE] [--allow-missing]
"""
import argparse
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KEXT = os.path.dirname(HERE)
PASCAL = os.path.dirname(KEXT)
ROOT = os.path.dirname(PASCAL)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("--firmware", default=os.path.join(ROOT, "research", "firmware"))
    ap.add_argument("--sha256", default=os.path.join(KEXT, "firmware.sha256"))
    ap.add_argument("--devboot", default=os.path.join(PASCAL, "core", "src", "devboot.c"))
    ap.add_argument("--allow-missing", action="store_true")
    a = ap.parse_args()

    pinned = {}
    for line in open(a.sha256):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        digest, path = line.split()
        pinned[path] = digest.lower()

    rows = re.findall(r'^\s*\{ "(gp106-[^"]+)", "([^"]+)"', open(a.devboot).read(), re.M)
    if not rows:
        sys.exit("gen-firmware-embed: no pg106_devboot_fw_names rows in %s" % a.devboot)

    out = []
    out.append("// Generated by pascal/kext/scripts/gen-firmware-embed.py. Do not edit.")
    out.append("// NVIDIA GP106 firmware from linux-firmware, unmodified (licence:")
    out.append("// licenses/NVIDIA-firmware-LICENCE.txt), checked against")
    out.append("// pascal/kext/firmware.sha256 at build time.")
    out.append('#include "pg106_fw_embedded.h"')
    out.append("")
    table = []
    missing = []
    for i, (resource, path) in enumerate(rows):
        full = os.path.join(a.firmware, path)
        want = pinned.get(path)
        if want is None:
            missing.append("%s: not in %s" % (path, os.path.basename(a.sha256)))
            continue
        if not os.path.isfile(full):
            missing.append("%s: file missing" % path)
            continue
        data = open(full, "rb").read()
        got = hashlib.sha256(data).hexdigest()
        if got != want:
            missing.append("%s: sha256 %s, pinned %s" % (path, got, want))
            continue
        if not data:
            missing.append("%s: empty" % path)
            continue
        name = "fw_%u_%s" % (i, re.sub(r"[^A-Za-z0-9]", "_", resource))
        out.append("// %s (%s): %u bytes, sha256 %s" % (resource, path, len(data), got))
        out.append("static const uint8_t %s[%u] = {" % (name, len(data)))
        for off in range(0, len(data), 16):
            out.append("\t" + " ".join("0x%02x," % b for b in data[off:off + 16]))
        out.append("};")
        table.append('\t{ "%s", "%s", %s, %uu, "%s" },' % (resource, path, name, len(data), got))
    if missing and not a.allow_missing:
        for m in missing:
            print("gen-firmware-embed: FAIL %s" % m, file=sys.stderr)
        sys.exit(1)
    for m in missing:
        print("gen-firmware-embed: note — %s (left out; OSKextRequestResource fallback)" % m, file=sys.stderr)
    out.append("")
    out.append("const struct pg106_fw_embedded pg106_fw_embedded[] = {")
    out.extend(table)
    out.append("};")
    out.append("const uint32_t pg106_fw_embedded_count = %uu;" % len(table))
    out.append("")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("\n".join(out))
    print("gen-firmware-embed: %u of %u blobs embedded -> %s" % (len(table), len(rows), a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
